import assert from 'node:assert/strict'
import test from 'node:test'
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { createJourneyStore, journeyIdentity, savedJourneyExecution } from '../../server/kane-journeys.mjs'
import { confirmKaneJourney } from '../../server/kane-worker.mjs'

const request = () => ({ taskId: 'connection-a', mode: 'action', url: 'https://example.com/books',
  objective: 'Exact guarded read objective', journey: { readOnly: true, sourceUrl: 'https://example.com/books',
    goal: 'Read current details', account: { status: 'public' }, requirements: { answer: 'current price', constraints: ['read only'] } } })
const source = () => ({ status: 'passed', browserId: 'private-browser-a', evidencePackPath: '/private/current.evidence',
  finalState: { access_state: 'public', result_fields_text: 'Price | fresh observation' } })
const analyzer = () => ({ status: 'passed', mode: 'analyzer', browserId: 'private-browser-a', allConditionsTrue: true,
  conditionResults: [{ result: true }] })

async function fixture(t) {
  const root = await mkdtemp(path.join(tmpdir(), 'raising-kane-journeys-'))
  t.after(() => rm(root, { recursive: true, force: true }))
  let clock = Date.now()
  return { store: createJourneyStore({ root, now: () => clock }), tick: ms => { clock += ms } }
}
async function recording(plan) {
  // Opaque bytes exercise cache storage only; this is not a runnable Kane test
  // and is never passed to Kane. Runtime definitions are generated by --name.
  await writeFile(plan.testPath, 'opaque CLI-owned definition bytes')
  await mkdir(path.join(plan.outputPath, '.internal'), { recursive: true })
  await writeFile(path.join(plan.outputPath, '.internal', 'meta.json'), '{}')
}

test('reuse requires exact public source, goal, requirements and guarded objective', () => {
  const input = request()
  const original = journeyIdentity(input)
  assert.ok(original)
  assert.equal(journeyIdentity({ ...input, taskId: 'another-browser' }).id, original.id)
  for (const mutation of [
    value => { value.objective += ' different' },
    value => { value.journey.goal += ' different' },
    value => { value.journey.requirements.answer = 'another requirement' },
    value => { value.url += '/next'; value.journey.sourceUrl = value.url },
  ]) {
    const value = structuredClone(input); mutation(value)
    assert.notEqual(journeyIdentity(value).id, original.id)
  }
  for (const mutation of [
    value => { value.journey.readOnly = false },
    value => { value.journey.account.status = 'signed_in'; value.journey.account.identity = 'different-user' },
    value => { value.journey.account.status = 'unknown' },
    value => { value.currentPage = true },
    value => { value.mode = 'testing' },
    value => { value.url += '?token=synthetic'; value.journey.sourceUrl = value.url },
    value => { value.journey.sourceUrl = 'https://other.example.com/books' },
    value => { value.journey.goal = 'Read using Bearer synthetic-test-value' },
  ]) {
    const value = structuredClone(input); mutation(value)
    assert.equal(journeyIdentity(value), null)
  }
})

test('recording becomes reusable only after a matching all-true independent source assessment', async t => {
  const { store } = await fixture(t)
  const plan = await store.prepare(request())
  assert.equal(plan.kind, 'record')
  await recording(plan)
  const result = await store.finish(plan, source())
  assert.equal(result.journey.status, 'candidate')
  assert.equal((await store.prepare(request())).kind, 'record', 'An unverified recording cannot be reused')
  await store.confirm({ result, verification: analyzer() })
  assert.equal(result.journey.status, 'proven')
  const replay = await store.prepare(request())
  assert.equal(replay.kind, 'replay')
  assert.notEqual(replay.testPath, plan.testPath, 'Each replay/heal receives a private copy')
  const manifest = JSON.parse(await readFile(plan.manifestPath, 'utf8'))
  assert.deepEqual(Object.keys(manifest).sort(), ['attempt', 'format', 'id', 'objectiveDigest', 'testDigest', 'verifiedAt'])
  assert.ok(!JSON.stringify(manifest).includes('fresh observation'), 'No old observation belongs in recipe metadata')
})

test('failed, missing, stale, wrong-browser and false analyzer verdicts cannot promote', async t => {
  const { store, tick } = await fixture(t)
  for (const verification of [undefined, { ...analyzer(), status: 'failed' },
    { ...analyzer(), allConditionsTrue: false }, { ...analyzer(), conditionResults: [{ result: false }] },
    { ...analyzer(), conditionResults: [{ result: null }] }, { ...analyzer(), conditionResults: [] },
    { ...analyzer(), browserId: 'wrong-browser' }]) {
    const plan = await store.prepare(request()); await recording(plan)
    const result = await store.finish(plan, source())
    await store.confirm({ result, verification })
    assert.equal(result.journey.status, 'not_saved')
    assert.equal((await store.prepare(request())).kind, 'record')
  }
  const plan = await store.prepare(request()); await recording(plan)
  const result = await store.finish(plan, source())
  tick(10 * 60 * 1000 + 1)
  await store.confirm({ result, verification: analyzer() })
  assert.equal(result.journey.status, 'not_saved')
})

test('healing may update recordings, but changed task text is refused and cannot poison the proven recipe', async t => {
  const { store } = await fixture(t)
  const first = await store.prepare(request()); await recording(first)
  const proven = await store.finish(first, source()); await store.confirm({ result: proven, verification: analyzer() })
  const replay = await store.prepare(request())
  await writeFile(replay.testPath, 'changed task requirements')
  const failed = await store.finish(replay, source(), { healed: true, replayDecisions: 1 })
  assert.equal(failed.status, 'error')
  assert.equal(failed.journey.mode, 'healed')
  assert.equal(failed.journey.requirementsPreserved, false)
  assert.deepEqual(failed.finalState, {})
  assert.equal((await store.prepare(request())).originalTestDigest, replay.originalTestDigest)
})

test('saved replay parser requires file completion and reports actual replay/heal decisions', () => {
  const partial = savedJourneyExecution([{ type: 'run_end', status: 'passed' }])
  assert.equal(partial.done, undefined)
  const result = savedJourneyExecution([
    { type: 'test_md_adaptive_heal', shrink_count: 1 },
    { type: 'test_md_summary', steps: { replay_decisions: 2, author_decisions: 1 }, adaptive_heal: { triggered: true } },
    { type: 'test_md_done', overall_status: 'failed' },
  ])
  assert.equal(result.done.overall_status, 'failed')
  assert.equal(result.healed, true)
  assert.equal(result.replayDecisions, 2)
  assert.equal(result.authorDecisions, 1)
})

test('stale and damaged recipe definitions cause fresh authoring', async t => {
  const { store, tick } = await fixture(t)
  const first = await store.prepare(request()); await recording(first)
  const proven = await store.finish(first, source()); await store.confirm({ result: proven, verification: analyzer() })
  await writeFile(first.testPath, 'modified outside the worker')
  assert.equal((await store.prepare(request())).kind, 'record')
  const second = await store.prepare(request()); await recording(second)
  const recent = await store.finish(second, source()); await store.confirm({ result: recent, verification: analyzer() })
  tick(7 * 24 * 60 * 60 * 1000 + 1)
  assert.equal((await store.prepare(request())).kind, 'record')
})

test('the worker refuses caller-invented analyzer objects as proof', async () => {
  const result = { ...source(), journey: { status: 'candidate' } }
  await confirmKaneJourney({ result, verification: analyzer() })
  assert.equal(result.journey.status, 'not_saved')
})
